// ---------- helpers ----------
function run(text, o = {}) {
  return new TextRun({ text, font: FONT, size: o.size || 24, bold: o.bold, italics: o.italics, allCaps: o.caps });
}
function p(text, o = {}) {
  const runs = Array.isArray(text) ? text : [run(text, o)];
  return new Paragraph({
    children: runs,
    alignment: o.align || AlignmentType.JUSTIFIED,
    indent: o.noIndent ? undefined : (o.indent !== undefined ? o.indent : { firstLine: mm(12.5) }),
    spacing: { before: o.before || 0, after: o.after !== undefined ? o.after : 0, line: o.line || 276 },
    keepNext: o.keepNext,
  });
}
function center(text, o = {}) { return p(text, { ...o, align: AlignmentType.CENTER, noIndent: true }); }
function h1(text) {
  return new Paragraph({ heading: HeadingLevel.HEADING_1, children: [run(text, { bold: true, caps: true })],
    alignment: AlignmentType.CENTER, spacing: { before: 0, after: 240 } });
}
function h2(text) {
  return new Paragraph({ heading: HeadingLevel.HEADING_2, children: [run(text, { bold: true })],
    alignment: AlignmentType.LEFT, indent: { firstLine: mm(12.5) }, spacing: { before: 200, after: 120 }, keepNext: true });
}
function h3(text) {
  return new Paragraph({ heading: HeadingLevel.HEADING_3, children: [run(text, { bold: true })],
    alignment: AlignmentType.LEFT, indent: { firstLine: mm(12.5) }, spacing: { before: 120, after: 120 }, keepNext: true });
}
function bullet(text, size = 24, ref = 'dash') {
  return new Paragraph({ numbering: { reference: ref, level: 0 }, children: [run(text, { size })],
    alignment: AlignmentType.JUSTIFIED, spacing: { line: 252 } });
}
function numbered(text, ref, size = 24) {
  return new Paragraph({ numbering: { reference: ref, level: 0 }, children: [run(text, { size })],
    alignment: AlignmentType.JUSTIFIED, spacing: { line: 276 } });
}
function pageBreak() { return new Paragraph({ children: [new PageBreak()] }); }

const TS = 22; // table font size (11 pt)
function cp(text, o = {}) {
  return new Paragraph({
    children: [run(text, { size: o.size || TS, bold: o.bold, italics: o.italics })],
    alignment: o.align || AlignmentType.LEFT, spacing: { line: 240 },
  });
}
function cell(content, w, o = {}) {
  let children;
  if (Array.isArray(content)) children = content.map(x => (typeof x === 'string' ? cp(x, o) : x));
  else children = [cp(content === undefined || content === null ? '' : String(content), o)];
  return new TableCell({
    children,
    width: { size: w, type: WidthType.DXA },
    columnSpan: o.colSpan, rowSpan: o.rowSpan,
    verticalAlign: o.vAlign || VerticalAlign.TOP,
    shading: o.shade ? { type: ShadingType.CLEAR, color: 'auto', fill: o.shade } : undefined,
    margins: { top: 40, bottom: 40, left: 80, right: 80 },
  });
}
function table(widths, rows) {
  const total = widths.reduce((a, b) => a + b, 0);
  return new Table({ width: { size: total, type: WidthType.DXA }, columnWidths: widths, rows });
}
function hdr(texts, widths) {
  return new TableRow({ tableHeader: true, children: texts.map((t, i) =>
    cell(t, widths[i], { bold: true, align: AlignmentType.CENTER, vAlign: VerticalAlign.CENTER, shade: 'EDEDED' })) });
}
function cellBullets(items, w, o = {}) {
  return new TableCell({
    children: items.map(t => new Paragraph({ numbering: { reference: 'cdash', level: 0 },
      children: [run(t, { size: TS })], spacing: { line: 240 } })),
    width: { size: w, type: WidthType.DXA }, columnSpan: o.colSpan, rowSpan: o.rowSpan,
    margins: { top: 40, bottom: 40, left: 80, right: 80 },
  });
}
